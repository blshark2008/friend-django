class Command(BaseCommand):
    help = 'Populate ExcludeKeyword table with existing EXCLUDE_KEYWORDS from views.py'

    def handle(self, *args, **options):
        created_count = 0
        skipped_count = 0

        for keyword, category in EXCLUDE_KEYWORDS_DATA:
            obj, created = ExcludeKeyword.objects.get_or_create(
                keyword=keyword,
                defaults={'category': category},
            )
            if created:
                created_count += 1
                self.stdout.write(
                    self.style.SUCCESS(f'Created: {keyword} ({category})')
                )
            else:
                skipped_count += 1

        self.stdout.write(self.style.SUCCESS(
            f'\nDone! Created: {created_count}, Skipped (already exists): {skipped_count}'
        ))
